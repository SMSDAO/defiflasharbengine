export function getTranslation(lang: SupportedLanguage, key: keyof typeof TRANSLATIONS['en'], params?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = (dict as any)[key] || TRANSLATIONS.en[key] || String(key);
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}
